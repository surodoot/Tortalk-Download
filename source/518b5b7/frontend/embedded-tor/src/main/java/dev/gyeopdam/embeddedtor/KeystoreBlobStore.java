package dev.gyeopdam.embeddedtor;

import android.content.Context;
import android.security.keystore.KeyGenParameterSpec;
import android.security.keystore.KeyProperties;
import android.util.AtomicFile;
import android.system.ErrnoException;
import android.system.Os;
import android.system.OsConstants;
import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileDescriptor;
import java.io.FileInputStream;
import java.io.FileNotFoundException;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.RandomAccessFile;
import java.nio.channels.FileChannel;
import java.nio.channels.FileLock;
import java.security.GeneralSecurityException;
import java.security.Key;
import java.security.KeyStore;
import java.util.Arrays;
import javax.crypto.KeyGenerator;
import javax.crypto.SecretKey;

/**
 * App-private, no-backup encrypted bytes. Call only on a worker thread.
 * Keys are generated by AndroidKeyStore on the device, on the first explicit write only.
 * Host tests exercise the envelope, not AndroidKeyStore, AtomicFile, hardware security or erasure.
 */
public final class KeystoreBlobStore {
    public static final int MAX_SIGNAL_BYTES = EncryptedBlobEnvelope.MAX_PAYLOAD_BYTES;
    public static final int MAX_BLOCK_BYTES = 256 * 1024;
    private static final Object PROCESS_LOCK = new Object();
    private static final String KEYSTORE = "AndroidKeyStore";
    private final Context context;
    private final String namespace;
    private final String alias;
    private final String domain;
    private final int limit;

    public KeystoreBlobStore(Context context, String namespace) {
        if (context == null || !("session".equals(namespace) || "config".equals(namespace) || ("signal".equals(namespace) || namespace != null && namespace.matches("signal-[0-9a-f]{64}")) || "enrollment".equals(namespace) || "device-recovery".equals(namespace)
                || namespace != null && namespace.matches("blocks-[0-9a-f]{64}"))) {
            throw new IllegalArgumentException("INVALID_STORAGE_NAMESPACE");
        }
        Context app = context.getApplicationContext();
        this.context = app == null ? context : app;
        String packageName = this.context.getPackageName();
        if (packageName == null || packageName.length() > 180
                || !packageName.matches("[A-Za-z0-9_.]+")) {
            throw new IllegalArgumentException("INVALID_STORAGE_CONTEXT");
        }
        this.namespace = namespace;
        this.alias = packageName + ".tortalk." + namespace + ".aes256gcm.v1";
        this.domain = "TorTalk/KeystoreBlob/v1/" + packageName + "/" + namespace;
        this.limit = namespace.matches("blocks-[0-9a-f]{64}") ? MAX_BLOCK_BYTES
                : ("signal".equals(namespace) || namespace.matches("signal-[0-9a-f]{64}")) ? MAX_SIGNAL_BYTES : SessionSchema.MAX_BYTES;
    }

    /** null means no persisted file. Missing keys, corruption and I/O errors are never absence. */
    public byte[] read() throws StorageException {
        return locked(this::readLocked);
    }

    /** Rejects corrupt or undecryptable existing state; explicit clear() is required to reset it. */
    public void write(byte[] plaintext) throws StorageException {
        write(plaintext, previous -> { });
    }

    /** Schema/binding validation shares the file lock with the commit; no read/write race. */
    void write(byte[] plaintext, PreviousValidator validator) throws StorageException {
        if (plaintext == null || plaintext.length > limit) throw failure(Code.INVALID_INPUT);
        // The caller owns its buffer. Freeze it before encryption to avoid concurrent mutation.
        byte[] snapshot = plaintext.clone();
        try {
            locked(file -> {
                byte[] previous = readLocked(file);
                try { validator.validate(previous); }
                finally { if (previous != null) Arrays.fill(previous, (byte) 0); }
                writeLocked(file, snapshot);
                return null;
            });
        } finally { Arrays.fill(snapshot, (byte) 0); }
    }

    /** Initializer runs only if state is absent, under the same lock as its durable commit. */
    byte[] readOrCreate(Initializer initializer) throws StorageException {
        return locked(file -> {
            byte[] previous = readLocked(file);
            if (previous != null) return previous;
            byte[] created = initializer.create();
            try {
                if (created == null || created.length > limit) throw failure(Code.INVALID_INPUT);
                writeLocked(file, created);
                return created.clone();
            } finally { if (created != null) Arrays.fill(created, (byte) 0); }
        });
    }

    private void writeLocked(AtomicFile file, byte[] plaintext) throws StorageException {
        SecretKey key = key(true);
        byte[] envelope;
        try { envelope = EncryptedBlobEnvelope.encrypt(key, domain, plaintext, limit); }
        catch (EncryptedBlobEnvelope.EnvelopeException ignored) { throw failure(Code.KEY_UNAVAILABLE); }
        FileOutputStream output = null;
        boolean commitAttempted = false;
        try {
            output = file.startWrite();
            output.write(envelope);
            // AtomicFile.finishWrite does sync, but reports some failures only in logs.
            // Explicitly propagate the fsync failure before replacing the previous file.
            output.getFD().sync();
            commitAttempted = true;
            file.finishWrite(output);
            output = null;
            byte[] committed = readEnvelope(file);
            if (committed == null || !Arrays.equals(envelope, committed)) throw failure(Code.IO_FAILED);
            syncDirectory(file.getBaseFile().getParentFile());
        } catch (IOException | RuntimeException ignored) {
            if (output != null) {
                if (!commitAttempted) {
                    try { file.failWrite(output); } catch (RuntimeException cleanupFailed) { /* Report uncertainty below. */ }
                } else {
                    // finishWrite may have renamed before throwing. Never roll back or
                    // delete that uncertain state; a later read must pass the durability barrier.
                    try { output.close(); } catch (IOException cleanupFailed) { /* Report uncertainty below. */ }
                }
            }
            throw failure(Code.IO_FAILED);
        }
    }

    /** Deletes the key first; an interrupted clear cannot leave readable old ciphertext. */
    public void clear() throws StorageException {
        locked(file -> {
            try {
                KeyStore store = openKeystore();
                if (store.containsAlias(alias)) store.deleteEntry(alias);
            } catch (GeneralSecurityException | IOException | RuntimeException ignored) {
                throw failure(Code.KEY_UNAVAILABLE);
            }
            file.delete();
            // API 26 and newer AtomicFile implementations use different recovery suffixes.
            // Every residue is ciphertext; none may survive a successful explicit clear.
            File base = file.getBaseFile();
            File[] residue = { base, new File(base.getPath() + ".bak"), new File(base.getPath() + ".new") };
            for (File candidate : residue) {
                if (candidate.exists() && !candidate.delete()) throw failure(Code.IO_FAILED);
                if (candidate.exists()) throw failure(Code.IO_FAILED);
            }
            syncDirectory(base.getParentFile());
            return null;
        });
    }

    private byte[] readLocked(AtomicFile file) throws StorageException {
        byte[] envelope = readEnvelope(file);
        if (envelope == null) return null;
        // AtomicFile may recover by rename. Also reconcile a previous commit whose
        // directory sync failed: no saved ratchet/outbox state is released until this succeeds.
        syncDirectory(file.getBaseFile().getParentFile());
        SecretKey existing = key(false);
        try { return EncryptedBlobEnvelope.decrypt(existing, domain, envelope, limit); }
        catch (EncryptedBlobEnvelope.EnvelopeException ignored) { throw failure(Code.CORRUPT_STATE); }
    }

    private static void syncDirectory(File directory) throws StorageException {
        if (directory == null) throw failure(Code.IO_FAILED);
        FileDescriptor descriptor = null;
        boolean failed = false;
        try {
            // O_DIRECTORY/O_CLOEXEC are not public API26 constants. Use the public
            // no-follow open plus descriptor type check instead of ABI-specific flag values.
            descriptor = Os.open(directory.getAbsolutePath(), OsConstants.O_RDONLY | OsConstants.O_NOFOLLOW, 0);
            if (!OsConstants.S_ISDIR(Os.fstat(descriptor).st_mode)) failed = true;
            else Os.fsync(descriptor);
        } catch (ErrnoException | RuntimeException ignored) {
            // A rename may already have committed. Preserve it and reject uncertain success.
            failed = true;
        } finally {
            if (descriptor != null) {
                try { Os.close(descriptor); }
                catch (ErrnoException | RuntimeException ignored) { failed = true; }
            }
        }
        if (failed) throw failure(Code.IO_FAILED);
    }

    private byte[] readEnvelope(AtomicFile file) throws StorageException {
        // Do not trust file length, allocate from an untrusted size, or treat unreadable as empty.
        try (FileInputStream input = file.openRead(); ByteArrayOutputStream bytes = new ByteArrayOutputStream()) {
            byte[] buffer = new byte[8192];
            int total = 0;
            int count;
            while ((count = input.read(buffer)) != -1) {
                total += count;
                if (total > limit + EncryptedBlobEnvelope.OVERHEAD_BYTES) throw failure(Code.CORRUPT_STATE);
                bytes.write(buffer, 0, count);
            }
            // A prior failed write/rollback may leave a complete but uncertain file.
            // Reconcile its data before the parent-directory barrier and plaintext release.
            input.getFD().sync();
            return bytes.toByteArray();
        } catch (FileNotFoundException ignored) {
            File base = file.getBaseFile();
            if (base.exists() || new File(base.getPath() + ".bak").exists()
                    || new File(base.getPath() + ".new").exists()) throw failure(Code.IO_FAILED);
            return null;
        } catch (StorageException expected) { throw expected; }
        catch (IOException | RuntimeException ignored) { throw failure(Code.IO_FAILED); }
    }

    private SecretKey key(boolean create) throws StorageException {
        try {
            KeyStore store = openKeystore();
            if (store.containsAlias(alias)) {
                Key key = store.getKey(alias, null);
                if (key instanceof SecretKey && KeyProperties.KEY_ALGORITHM_AES.equals(key.getAlgorithm())) {
                    return (SecretKey) key;
                }
                throw failure(Code.KEY_UNAVAILABLE);
            }
            if (!create) throw failure(Code.KEY_UNAVAILABLE);
            KeyGenerator generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE);
            generator.init(new KeyGenParameterSpec.Builder(alias,
                    KeyProperties.PURPOSE_ENCRYPT | KeyProperties.PURPOSE_DECRYPT)
                    .setKeySize(256)
                    .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                    .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                    .setRandomizedEncryptionRequired(true)
                    .build());
            return generator.generateKey();
        } catch (StorageException expected) { throw expected; }
        catch (GeneralSecurityException | IOException | RuntimeException ignored) { throw failure(Code.KEY_UNAVAILABLE); }
    }

    private static KeyStore openKeystore() throws GeneralSecurityException, IOException {
        KeyStore store = KeyStore.getInstance(KEYSTORE);
        store.load(null);
        return store;
    }

    private <T> T locked(Operation<T> operation) throws StorageException {
        // AtomicFile does not provide locking. The monitor coordinates store instances, and
        // the OS lock also protects against another app process using this same implementation.
        synchronized (PROCESS_LOCK) {
            try {
                File directory = context.getNoBackupFilesDir();
                if (directory == null || !directory.isDirectory()) throw failure(Code.IO_FAILED);
                File base = new File(directory, "tortalk-" + namespace + "-v1.enc");
                File lockPath = new File(directory, "tortalk-" + namespace + "-v1.lock");
                try (RandomAccessFile lockFile = new RandomAccessFile(lockPath, "rw");
                     FileChannel channel = lockFile.getChannel();
                     FileLock lock = channel.lock()) {
                    if (!lock.isValid()) throw failure(Code.IO_FAILED);
                    return operation.run(new AtomicFile(base));
                }
            } catch (StorageException expected) { throw expected; }
            catch (IOException | RuntimeException ignored) { throw failure(Code.IO_FAILED); }
        }
    }

    private interface Operation<T> { T run(AtomicFile file) throws StorageException; }
    interface PreviousValidator { void validate(byte[] previous) throws StorageException; }
    interface Initializer { byte[] create() throws StorageException; }
    public enum Code { INVALID_INPUT, CORRUPT_STATE, KEY_UNAVAILABLE, IO_FAILED, ORIGIN_MISMATCH, IDENTITY_MISMATCH }
    private static StorageException failure(Code code) { return new StorageException(code); }

    public static final class StorageException extends IOException {
        private static final long serialVersionUID = 1L;
        public final Code code;
        StorageException(Code code) { super(code.name()); this.code = code; }
    }

    @Override public String toString() { return "KeystoreBlobStore([redacted])"; }
}
